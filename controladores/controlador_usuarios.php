<?php

class controlador_usuarios extends controlador{

    public $grupos = array();
    public $carreras = array();

    public $usuario_carrera_modelo;

    public function __construct(database $link){

        parent::__construct($link,'usuarios');

        $this->configuracion();
    }

    private function configuracion(){

        $grupo_modelo = new grupos($this->link);
        $carrera_modelo = new carreras($this->link);
        $this->usuario_carrera_modelo = new usuario_carrera($this->link);

        $this->grupos = $grupo_modelo->filtro_and(array('status'=>'activo'),
            array('id','descripcion_grupo'))['registros'];

        $this->carreras = $carrera_modelo->filtro_and(array('status'=>'activo'),
            array('id','nombre'))['registros'];

        $this->valida_campos_unicos = array(
            'usuario' => 'user'
        );

    }// end configuracion

    public function alta(){

        $this->inputs[] = $this->HTML->input('Nombre','nombre',4,
            'Nombre');

        $this->inputs[] = $this->HTML->input('Apellido P','apellido_p',4,
            'Apellido P');

        $this->inputs[] = $this->HTML->input('Apellido M','apellido_m',4,
            'Apellido M');

        $this->inputs[] = $this->HTML->input('Usuario','user',4,'Correo','@itesco.edu.mx',
            'email');

        $this->inputs[] = $this->HTML->input('Contraseña','password',4,
            'Contraseña');

        $this->inputs[] = $this->HTML->select('Tipo Usuario','grupo_id',
            4,$this->grupos,'descripcion_grupo','4');

        $this->inputs[] = $this->HTML->select_multiple('Carrera','carreras_ids[]',
            8,$this->carreras,'nombre');

        $this->inputs[] = $this->HTML->submit('Registrar','usuarios_alta_bd',4);

    }// end alta


    public function alta_bd(bool $header = false){

        $this->link->dbh->beginTransaction();

        $carreras_ids = $_POST['carreras_ids'];
        unset($_POST['carreras_ids']);

        $resultado = parent::alta_bd($header); // TODO: Change the autogenerated stub
        $usuario_id = $resultado['registro_id'];

        if (isset($resultado['error'])){
            $this->link->dbh->rollBack();
            $error = $this->errores->datos(1,'Error, al registrar',
                __CLASS__,__LINE__,__FILE__,$resultado,__FUNCTION__);
            print_r($error);
            exit;
        }

        foreach ($carreras_ids as $carrera_id){
            $insert['usuario_id'] = $usuario_id;
            $insert['carrera_id'] = $carrera_id;
            $insert['status'] = 'activo';
            $insert['usuario_alta_id'] = USUARIO_ID;
            $insert['usuario_update_id'] = USUARIO_ID;

            $resultado_alta = $this->usuario_carrera_modelo->alta_bd($insert);

            if (isset($resultado_alta['error'])){
                $this->link->dbh->rollBack();
                $error = $this->errores->datos(1,'Error, al registar en usuario_carrera',
                    __CLASS__,__LINE__,__FILE__,$resultado_alta,__FUNCTION__);
                print_r($error);
                exit;
            }
        }

        $this->link->dbh->commit();
        header_url($this->tabla,'lista',SESSION_ID,'registro exitoso');
        exit;
    }

    public function modifica(){
        parent::modifica();

        $usuario_id = $_GET['registro_id'];

        $filtro = array('usuario_id' => $usuario_id);
        $resultado_busqueda = $this->usuario_carrera_modelo->filtro_and($filtro,array('carrera_id'));

        if (isset($resultado_busqueda['error'])){
            $error = $this->errores->datos(1,'Error, al consultar carreras',
                __CLASS__,__LINE__,__FILE__,$resultado_busqueda,__FUNCTION__);
            print_r($error);
            exit;
        }
        $carreras_ids = array();
        foreach ($resultado_busqueda['registros'] as $registo){
            $carreras_ids[] = $registo['carrera_id'];
        }

        $this->inputs[] = $this->HTML->input('Nombre','nombre',4,
            'Nombre',$this->registro['nombre']);

        $this->inputs[] = $this->HTML->input('Apellido P','apellido_p',4,
            'Apellido P',$this->registro['apellido_p']);

        $this->inputs[] = $this->HTML->input('Apellido M','apellido_m',4,
            'Apellido M',$this->registro['apellido_m']);

        $this->inputs[] = $this->HTML->input('Usuario','user',4,'Correo',
            $this->registro['user'],'email');

        $this->inputs[] = $this->HTML->input('Contraseña','password',4,
            'Contraseña',$this->registro['password']);

        $this->inputs[] = $this->HTML->select('Tipo Usuario','grupo_id',
            4,$this->grupos,'descripcion_grupo',$this->registro['grupo_id']);

        $this->inputs[] = $this->HTML->select_multiple('Carrera','carreras_ids[]',
            8,$this->carreras,'nombre',$carreras_ids);

        $this->inputs[] = $this->HTML->submit('Modificar','usuarios_modifica_bd',4);
    }// end modifica

    public function modifica_bd(bool $header = false){
        $this->link->dbh->beginTransaction();

        $carreras_ids = $_POST['carreras_ids'];
        unset($_POST['carreras_ids']);

        $resultado = parent::modifica_bd($header); // TODO: Change the autogenerated stub
        $usuario_id = $_GET['registro_id'];

        if (isset($resultado['error'])){
            $this->link->dbh->rollBack();
            $error = $this->errores->datos(1,'Error, al registrar',
                __CLASS__,__LINE__,__FILE__,$resultado,__FUNCTION__);
            print_r($error);
            exit;
        }

        $resultado_elimina = $this->usuario_carrera_modelo->elimina_con_filtro_and(
            array('usuario_id' => $usuario_id));

        if (isset($resultado_elimina['error'])){
            $this->link->dbh->rollBack();
            $error = $this->errores->datos(1,'Error, al eliminar registro de usuario_carrera',
                __CLASS__,__LINE__,__FILE__,$resultado_elimina,__FUNCTION__);
            print_r($error);
            exit;
        }

        foreach ($carreras_ids as $carrera_id){
            $insert['usuario_id'] = $usuario_id;
            $insert['carrera_id'] = $carrera_id;
            $insert['status'] = 'activo';
            $insert['usuario_alta_id'] = USUARIO_ID;
            $insert['usuario_update_id'] = USUARIO_ID;

            $resultado_alta = $this->usuario_carrera_modelo->alta_bd($insert);

            if (isset($resultado_alta['error'])){
                $this->link->dbh->rollBack();
                $error = $this->errores->datos(1,'Error, al registar en usuario_carrera',
                    __CLASS__,__LINE__,__FILE__,$resultado_alta,__FUNCTION__);
                print_r($error);
                exit;
            }
        }

        $this->link->dbh->commit();
        header_url($this->tabla,'lista',SESSION_ID,'registro modificado');
        exit;



    }

    public function lista(){

        // configuracion de el filtro para la lista
        $this->lista_usar_filtro = true;
        $this->inputs_filtro_lista_cols = 2;

        $this->filtro_lista_campos = array(
            'Nombre' => 'usuarios.nombre',
            'Apellido P' => 'usuarios.apellido_p',
            'Apellido M' => 'usuarios.apellido_m',
            'Usuario' => 'usuarios.user',
            'Tipo Usuario' => 'grupos.descripcion_grupo'
        );
        // termina configuracion de el filtro para la lista

        $this->nombre_columnas_lista = array('ID','Nombre','Apellido P','Apellido M','Usuario','Tipo Usuario','Estatus');
        $this->columnas_lista = array('usuarios.id','usuarios.nombre','usuarios.apellido_p','usuarios.apellido_m','user','grupos.descripcion_grupo',
            'usuarios.status');
        $this->joins_lista = ' LEFT JOIN grupos ON usuarios.grupo_id = grupos.id ';

        parent::lista();

    }// end lista


}